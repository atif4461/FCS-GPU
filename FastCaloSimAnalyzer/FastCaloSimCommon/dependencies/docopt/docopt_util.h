/**
 * Checks if a string starts with a specified prefix.
 *
 * @param str The input string to check.
 * @param prefix The prefix to search for at the start of the string.
 * @return True if the string starts with the prefix, false otherwise.
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.5.
*/ 
	bool starts_with(std::string const& str, std::string const& prefix)
	{
		if (str.length() < prefix.length())
			return false;
		return std::equal(prefix.begin(), prefix.end(),
				  str.begin());
  }

/**
 * Removes leading and trailing whitespace from a given string.
 *
 * @param str The input string to be trimmed.
 * @param whitespace A string containing characters considered as whitespace.
 * @return The trimmed string with no leading or trailing whitespace.
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.5.
*/ 
	std::string trim(std::string&& str,
			 const std::string& whitespace = " \t\n")
	{
    const auto strEnd = str.find_last_not_of( whitespace );
		if (strEnd==std::string::npos)
			return {}; // no content
    str.erase( strEnd + 1 );

    const auto strBegin = str.find_first_not_of( whitespace );
    str.erase( 0, strBegin );

    return std::move( str );
  }

/**
 * Splits a string into substrings separated by spaces
 *
 * @param str The input string to be split
 * @param pos The starting position in the string
 * @return A vector of substrings
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.5.
*/ 
	std::vector<std::string> split(std::string const& str, size_t pos = 0)
	{
    const char* const anySpace = " \t\r\n\v\f";

    std::vector<std::string> ret;
    while ( pos != std::string::npos ) {
      auto start = str.find_first_not_of( anySpace, pos );
      if ( start == std::string::npos ) break;

      auto end  = str.find_first_of( anySpace, start );
      auto size = end == std::string::npos ? end : end - start;
      ret.emplace_back( str.substr( start, size ) );

      pos = end;
    }

    return ret;
  }

/**
 * Function to partition a given string around a specified point.
 *
 * @param str The input string to be partitioned.
 * @param point The point around which the string is to be partitioned.
 * @return A tuple containing three strings representing the part of the string before the point, the point itself, and the part of the string after the point.
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.5.
*/ 
	std::tuple<std::string, std::string, std::string> partition(std::string str, std::string const& point)
	{
    std::tuple<std::string, std::string, std::string> ret;

    auto i = str.find( point );

    if ( i == std::string::npos ) {
      // no match: string goes in 0th spot only
    } else {
      std::get<2>( ret ) = str.substr( i + point.size() );
      std::get<1>( ret ) = point;
      str.resize( i );
    }
    std::get<0>( ret ) = std::move( str );

    return ret;
  }

  template <typename I>
/**
 * Function to concatenate a range of strings with a specified delimiter
 * @param iter   Iterator pointing to the beginning of the string range
 * @param end    Iterator pointing to the end of the string range
 * @param delim  Delimiter to be used between concatenated strings
 * @return Concatenated string
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.5.
*/ 
  std::string join( I iter, I end, std::string const& delim ) {
		if (iter==end)
			return {};

    std::string ret = *iter;
    for ( ++iter; iter != end; ++iter ) {
      ret.append( delim );
      ret.append( *iter );
    }
    return ret;
  }

/**
 * Function to split input string into substrings based on regular expression
 * @param text Input string to be split
 * @param re Regular expression used for splitting
 * @return Vector of strings resulting from split operation
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.5.
*/ 
	std::vector<std::string> regex_split(std::string const& text, std::regex const& re)
	{
    std::vector<std::string> ret;
		for (auto it = std::sregex_token_iterator(text.begin(), text.end(), re, -1);
			it != std::sregex_token_iterator();
          ++it ) {
      ret.emplace_back( *it );
    }
    return ret;
  }
